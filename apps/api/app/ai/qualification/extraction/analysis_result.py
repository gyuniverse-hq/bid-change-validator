def _canonical_diagnostic(raw: dict[str, Any]) -> AnalysisDiagnostic:
    code = str(raw.get("code") or "CANONICALIZATION_WARNING")
    return AnalysisDiagnostic(
        code=code,
        severity="WARNING",
        message=_DIAGNOSTIC_MESSAGES.get(code, "Canonical 변환 과정에서 확인이 필요합니다."),
        details={key: value for key, value in raw.items() if key != "code"},
    )


def build_requirement_analysis_result(
    *,
    notice_id: str,
    notice_version_id: str,
    document_ids: list[str],
    canonicalized: dict[str, Any],
    extraction_status: str = "ok",
    extraction_notes: str = "",
    extraction_dropped_requirements: list[dict[str, str]] | None = None,
    target_chunk_ids: list[str] | None = None,
) -> RequirementAnalysisResult:
    """Build the stable Backend-facing payload from current pipeline outputs."""
    requirements = list(canonicalized.get("requirements") or [])
    evidence = list(canonicalized.get("evidence") or [])
    diagnostics = [
        _canonical_diagnostic(item)
        for item in list(canonicalized.get("diagnostics") or [])
    ]

    if extraction_status != "ok":
        diagnostics.insert(
            0,
            AnalysisDiagnostic(
                code="EXTRACTION_PARTIAL" if extraction_status == "partial" else "EXTRACTION_FAILED",
                severity="WARNING" if extraction_status == "partial" else "ERROR",
                message="구조화 Requirement 추출 단계가 완료되지 않았습니다.",
                details={
                    "status": extraction_status,
                    "notes": extraction_notes,
                },
            ),
        )
        status: AnalysisStatus = "PARTIAL" if requirements or evidence else "FAILED"
    elif diagnostics:
        status = "PARTIAL"
    else:
        status = "SUCCEEDED"

    if extraction_status == "ok" and extraction_notes:
        diagnostics.append(
            AnalysisDiagnostic(
                code="EXTRACTION_NOTES",
                severity="INFO",
                message="Requirement 추출 단계에 추가 검증 메모가 있습니다.",
                details={"notes": extraction_notes},
            )
        )

    if status == "FAILED":
        requirements = []
        evidence = []

    return RequirementAnalysisResult(
        status=status,
        notice_id=notice_id,
        notice_version_id=notice_version_id,
        document_ids=document_ids,
        target_chunk_ids=list(target_chunk_ids or []),
        requirements=requirements,
        evidence=evidence,
        diagnostics=diagnostics,
        dropped_requirements=list(extraction_dropped_requirements or []),
    )
