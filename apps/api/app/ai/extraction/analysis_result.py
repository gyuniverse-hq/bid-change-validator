"""Backend-facing AI output contract for qualification requirement analysis.

This is the boundary object returned after semantic chunking, structured
extraction, source-grounding validation, and canonicalization. It intentionally
contains no database primary keys generated by AI and no model-specific payload.
Backend-owned notice/document identifiers remain the source of truth.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field, model_validator

from ..contracts import Evidence, QualificationRequirement


AnalysisStatus = Literal["SUCCEEDED", "PARTIAL", "FAILED"]
AnalysisKind = Literal["QUALIFICATION_REQUIREMENTS"]
DiagnosticSeverity = Literal["INFO", "WARNING", "ERROR"]
DroppedReasonCode = Literal[
    "MISSING_RAW",
    "RAW_NOT_FOUND_IN_SOURCE",
    "DETAIL_NOT_FOUND_IN_SOURCE",
    "SOURCE_VALIDATION_FAILED",
]


# 진단에는 성격이 다른 두 가지가 섞여 있다. 파이프라인이 제 일을 못 한 것과,
# 공고에 그렇게 적혀 있어서 판정 대상이 아닌 것은 사용자에게 완전히 다른 뜻이다.
# 전자만 분석 품질 저하(PARTIAL)로 봐야 하고, 후자는 정상 결과다.
DiagnosticKind = Literal[
    "PIPELINE",      # 추출·구조화가 실패했다. 요건을 잃은 것이므로 PARTIAL.
    "NOTICE_FACT",   # 공고에서 확인했으나 회사 프로필과 대조할 성질이 아니다.
]


class AnalysisDiagnostic(BaseModel):
    code: str
    severity: DiagnosticSeverity = "WARNING"
    message: str
    details: dict[str, Any] = Field(default_factory=dict)
    kind: DiagnosticKind = "PIPELINE"
    # NOTICE_FACT 는 원문 근거를 달고 다녀야 한다. 근거 없는 "확인했음"은
    # 사용자가 검증할 수 없어서 "확인 안 했음"과 구별되지 않는다.
    evidence_keys: list[str] = Field(default_factory=list)


class DroppedRequirement(BaseModel):
    """An extracted candidate rejected by deterministic source validation."""

    raw: str
    reason_code: DroppedReasonCode


class RequirementAnalysisResult(BaseModel):
    """Canonical AI -> Backend result for one notice version."""

    contract_version: Literal["ai-analysis-v0.2"] = "ai-analysis-v0.2"
    analysis_kind: AnalysisKind = "QUALIFICATION_REQUIREMENTS"
    status: AnalysisStatus
    notice_id: str
    notice_version_id: str
    document_ids: list[str] = Field(default_factory=list)
    target_chunk_ids: list[str] = Field(default_factory=list)
    requirements: list[QualificationRequirement] = Field(default_factory=list)
    evidence: list[Evidence] = Field(default_factory=list)
    diagnostics: list[AnalysisDiagnostic] = Field(default_factory=list)
    dropped_requirements: list[DroppedRequirement] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_internal_links(self) -> "RequirementAnalysisResult":
        if len(self.document_ids) != len(set(self.document_ids)):
            raise ValueError("document_ids must be unique")

        requirement_keys = [item.requirement_key for item in self.requirements]
        if len(requirement_keys) != len(set(requirement_keys)):
            raise ValueError("requirement_key values must be unique")

        evidence_keys = [item.evidence_key for item in self.evidence]
        if len(evidence_keys) != len(set(evidence_keys)):
            raise ValueError("evidence_key values must be unique")
        evidence_key_set = set(evidence_keys)
        document_id_set = set(self.document_ids)

        for requirement in self.requirements:
            if requirement.notice_version_id != self.notice_version_id:
                raise ValueError(
                    "requirement notice_version_id must match analysis notice_version_id"
                )
            unresolved = set(requirement.evidence_keys) - evidence_key_set
            if unresolved:
                raise ValueError(
                    f"requirement contains unresolved evidence keys: {sorted(unresolved)}"
                )

        for item in self.evidence:
            if item.notice_version_id != self.notice_version_id:
                raise ValueError(
                    "evidence notice_version_id must match analysis notice_version_id"
                )
            if item.document_id not in document_id_set:
                raise ValueError(
                    f"evidence document_id is outside analysis scope: {item.document_id}"
                )

        if self.status == "FAILED" and (self.requirements or self.evidence):
            raise ValueError("FAILED analysis must not expose canonical results")

        return self


